const fmt = (n: number) => n.toLocaleString('en-US')
const shape = (s: number[]) => `${s[0]} × ${s[1]} × ${s[2]}`

function jump(id: string) {
  const heading = document.getElementById(`${id}-title`)
  heading?.scrollIntoView({ block: 'start' })
  heading?.focus({ preventScroll: true })
}

/** The circuit drawing, inlined so its lines follow the page's text colour. */
function CircuitFigure() {
  const [svg, setSvg] = useState<string | null>(null)
  useEffect(() => {
    let live = true
    fetch(dataUrl('lab/qcnn_circuit.svg'))
      .then((r) => (r.ok ? r.text() : Promise.reject(new Error(String(r.status)))))
      .then((t) => live && setSvg(t))
      .catch(() => live && setSvg(''))
    return () => {
      live = false
    }
  }, [])
  return (
    <figure className="circuit">
      {/* The SVG is generated by export_internals.py from this repository's own circuit; nothing user-supplied. */}
      <div
        className="circuit-scroll"
        role="img"
        aria-label="QCNN circuit on 8 qubits: RY angle encoding, then three convolution stages of RY and RZ rotations with entangling gates, two pooling stages, and measurements on the remaining qubits"
        tabIndex={0}
        dangerouslySetInnerHTML={svg ? { __html: svg } : undefined}
      >
        {svg === null ? <p className="lab-muted">Loading the circuit…</p> : svg === '' ? <p className="lab-muted">The circuit drawing could not be loaded.</p> : undefined}
      </div>
      <figcaption>
        Drawn by <span className="mono">qml.draw_mpl</span> from <span className="mono">BatchedQCNNHead.circuit</span>, the
        one circuit used on Mars and on the Moon. Scroll sideways to follow it. Gate angles are left off the drawing; the
        trained values are in the heatmaps below.
      </figcaption>
    </figure>
  )
}

function Projection({ p, title }: { p: LabProjection; title: string }) {
  return (
    <div className="projection">
      <h4>{title}</h4>
      <p className="projection-dims" aria-label={`${p.in_dim} numbers to ${p.out_dim} numbers to ${p.out_dim} qubit angles`}>
        <span>{p.in_dim}</span>
        <span aria-hidden="true">→</span>
        <span>{p.out_dim}</span>
        <span aria-hidden="true">→</span>
        <span>{p.out_dim} angles</span>
      </p>
      <ol>
        {p.notes.map((n) => (
          <li key={n}>{n}</li>
        ))}
      </ol>
      <p className="mono projection-formula">θ = (tanh(z) + 1) · π / 2</p>
    </div>
  )
}

function Excerpt({ e }: { e: LabExcerpt }) {
  return (
    <article className="excerpt" data-excerpt={e.id} data-topic={e.world}>
      <header className="excerpt-head">
        <h3>{e.title}</h3>
        <p className="excerpt-path mono">
          {e.path} · lines {e.start} to {e.end}
        </p>
      </header>
      <p className="excerpt-note">{e.note}</p>
      <div className="excerpt-code" tabIndex={0} aria-label={`${e.path}, lines ${e.start} to ${e.end}`}>
        {e.html ? (
          <div dangerouslySetInnerHTML={{ __html: e.html }} />
        ) : (
          <pre style={{ '--line-start': e.start } as CSSProperties}>
            <code>{e.code}</code>
          </pre>
        )}
      </div>
      <p className="excerpt-link">
        <a href={e.permalink}>Open these lines on GitHub</a>
      </p>
      {e.history_note && (
        <details className="history" data-history-note>
          <summary>Code history: train.py and the reported runs</summary>
          <div className="history-body">
            {e.history_note.html ? (
              <div dangerouslySetInnerHTML={{ __html: e.history_note.html }} />
            ) : (
              <pre className="history-text">{e.history_note.text}</pre>
            )}
            <p>
              <a href={e.history_note.permalink}>The note in experiments/moon/README.md</a>
            </p>
          </div>
        </details>
      )}
    </article>
  )
}

